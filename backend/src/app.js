import express from 'express';
import cors from 'cors';
import { env } from './config/env.js';
import { sqlErrorHandler } from './lib/http.js';
import authRoutes from './modules/auth.js';
import adminRoutes from './modules/admin.js';
import librosRoutes from './modules/libros.js';
import prestamosRoutes from './modules/prestamos.js';
import usuariosRoutes from './modules/usuarios.js';
import multasRoutes from './modules/multas.js';
import incidenciasRoutes from './modules/incidencias.js';
import avisosRoutes from './modules/avisos.js';
import credencialesRoutes from './modules/credenciales.js';
const app=express();
app.disable('x-powered-by');
app.use(express.json({limit:'64kb'}));
app.use(cors({origin:env.origin ? env.origin.split(',') : false}));
app.get('/api/salud',(_req,res)=>res.json({ok:true,aplicacion:'BiblioApp API'}));
app.use('/api',authRoutes);
app.use('/api/admin',adminRoutes);
app.use('/api/libros',librosRoutes);
app.use('/api/prestamos',prestamosRoutes);
app.use('/api/usuarios',usuariosRoutes);
app.use('/api/multas',multasRoutes);
app.use('/api/incidencias',incidenciasRoutes);
app.use('/api/avisos',avisosRoutes);
app.use('/api/credenciales',credencialesRoutes);
app.use((_req,res)=>res.status(404).json({mensaje:'Ruta no encontrada.'}));
app.use(sqlErrorHandler);
export default app;
